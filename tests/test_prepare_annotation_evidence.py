@pytest.mark.parametrize("extras,native_frames", [(None, [2, 4, 5]), ([4, 3], [2, 3, 4, 5])])
def test_clip_preserves_native_pixels_clock_and_explicit_frame_offset(raw, tmp_path, extras, native_frames):
    source, views, _, _, pixels = raw
    settings = {"views": views, "task": "Synthetic tool placement", "task_instruction": "Place the tool.",
                "stage_semantics": "active_subtask",
                "task_policy": {"version": "synthetic", "status": "draft", "rules": "Unknown unless visible."},
                "registry": [{"id": "S1", "label": "1", "prompt": "Place the tool"}]}
    output = tmp_path / "evidence"
    helper.prepare(source, 0, settings, output, start_frame=2, end_frame=6,
                   stride_seconds=.15, max_images=len(native_frames), tile_size=(32, 24),
                   extra_frames=extras)
    bundle = json.loads((output / "bundle.json").read_text())
    records = json.loads((output / "evidence.json").read_text())["images"]
    assert bundle["context"]["time_edges"] == pytest.approx([10.2, 10.3, 10.4, 10.5, 10.6])
    assert bundle["context"]["source_identity"]["source_frame_range"] == [2, 6]
    candidate_frames = [frame - 2 for frame in native_frames]
    assert bundle["context"]["evidence_frames"] == candidate_frames
    for row, native_frame in zip(records, native_frames, strict=True):
        assert row["frame"] == native_frame - 2
        assert row["timestamp"] == pytest.approx(10 + native_frame / 10)
        image = np.asarray(Image.open(row["image_path"]))
        for camera, view in enumerate(views):
            np.testing.assert_array_equal(image[24:48, camera * 32:(camera + 1) * 32], pixels[view][native_frame])
    receipt = json.loads((output / "source_receipt.json").read_text())
    assert receipt["annotation_columns_read"] is False
    assert receipt["sampling"]["source_frames"] == native_frames
    assert receipt["sampling"]["extra_source_frames"] == sorted(extras or [])
    assert receipt["sampling"]["extra_candidate_frames"] == [frame - 2 for frame in sorted(extras or [])]
    assert receipt["sampling"]["grid_origin_seconds"] == pytest.approx(10.2)
    assert receipt["sampling"]["max_images"] == len(native_frames)
    # The API driver accepts the exact generated bytes and clip-local clock
    # without any network request or exposure of original paths/identities.
    frozen, content, verified = prepare_request(output / "bundle.json", output / "evidence.json")
    assert frozen == bundle
    assert [row["frame"] for row in verified] == candidate_frames
    assert [row["timestamp"] for row in verified] == pytest.approx([10 + frame / 10 for frame in native_frames])
    wire_context = json.loads(content[0]["text"].split("\n", 1)[1])
    assert "source_identity" not in wire_context
    assert wire_context["time_edges"] == bundle["context"]["time_edges"]
    assert len([row for row in content if row["type"] == "input_image"]) == len(native_frames)


